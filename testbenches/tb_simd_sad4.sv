`timescale 1ns / 1ps



module tb_simd_sad();

    // --------------------------------------------------------
    // DUT Signals
    // --------------------------------------------------------
    logic [31:0] operand_a;
    logic [31:0] operand_b;
    logic [31:0] result;

    // --------------------------------------------------------
    // DUT Instance
    // --------------------------------------------------------
    simd_sad dut (
        .operand_a (operand_a),
        .operand_b (operand_b),
        .result    (result)
    );

    // --------------------------------------------------------
    // Test Task
    // --------------------------------------------------------
    task automatic check_sad4 (
        input logic [31:0] a,
        input logic [31:0] b,
        input logic [31:0] expected
    );
        begin
            operand_a = a;
            operand_b = b;

            #1;

            if (result === expected) begin
                $display(
                    "PASS | A = %h | B = %h | Result = %0d",
                    operand_a,
                    operand_b,
                    result
                );
            end
            else begin
                $display(
                    "FAIL | A = %h | B = %h | Expected = %0d | Got = %0d",
                    operand_a,
                    operand_b,
                    expected,
                    result
                );
            end
        end
    endtask


    // --------------------------------------------------------
    // Test Sequence
    // --------------------------------------------------------
    initial begin

        $display("========================================");
        $display("        SIMD SAD4 Testbench");
        $display("========================================");

        // ----------------------------------------------------
        // Test 1: Identical values
        // SAD = 0
        // ----------------------------------------------------
        check_sad4(
            32'h12345678,
            32'h12345678,
            32'd0
        );


        // ----------------------------------------------------
        // Test 2: Simple example
        //
        // A = [100, 120, 80, 50]
        // B = [105, 118, 95, 52]
        //
        // |100 - 105| = 5
        // |120 - 118| = 2
        // |80  - 95 | = 15
        // |50  - 52 | = 2
        //
        // SAD = 24
        // ----------------------------------------------------
        check_sad4(
            {8'd100, 8'd120, 8'd80, 8'd50},
            {8'd105, 8'd118, 8'd95, 8'd52},
            32'd24
        );


        // ----------------------------------------------------
        // Test 3: Maximum possible SAD
        //
        // A = [255, 255, 255, 255]
        // B = [0,   0,   0,   0]
        //
        // SAD = 4 × 255 = 1020
        // ----------------------------------------------------
        check_sad4(
            32'hFFFFFFFF,
            32'h00000000,
            32'd1020
        );


        // ----------------------------------------------------
        // Test 4: Reverse maximum
        //
        // Checks that |A-B| works correctly
        // when B is greater than A
        // ----------------------------------------------------
        check_sad4(
            32'h00000000,
            32'hFFFFFFFF,
            32'd1020
        );


        // ----------------------------------------------------
        // Test 5: Mixed values
        //
        // A = [10, 20, 30, 40]
        // B = [15, 10, 35, 20]
        //
        // |10 - 15| = 5
        // |20 - 10| = 10
        // |30 - 35| = 5
        // |40 - 20| = 20
        //
        // SAD = 40
        // ----------------------------------------------------
        check_sad4(
            {8'd10, 8'd20, 8'd30, 8'd40},
            {8'd15, 8'd10, 8'd35, 8'd20},
            32'd40
        );


        $display("========================================");
        $display("        Testbench Finished");
        $display("========================================");

        $finish;
    end

endmodule


