# ============================================================
#  SAD4 - Standard RV32I
#
# Input:
#   x1 = 0x64785032
#   x2 = 0x69765F34
#
# Output:
#   x3 = SAD Result (24)
#
# RV32I instructions only
# ============================================================


# ------------------------------------------------------------
# Initialize Operands
# ------------------------------------------------------------

    lui   x1, 0x64785
    addi  x1, x1, 0x032

    lui   x2, 0x69766
    addi  x2, x2, -204


# ------------------------------------------------------------
# Byte 0
# ------------------------------------------------------------

    andi  x6, x1, 255
    andi  x7, x2, 255

    sub   x3, x7, x6
    bgeu  x7, x6, BYTE0_DONE
    sub   x3, x6, x7

BYTE0_DONE:


# ------------------------------------------------------------
# Byte 1
# ------------------------------------------------------------

    srli  x6, x1, 8
    srli  x7, x2, 8

    andi  x6, x6, 255
    andi  x7, x7, 255

    sub   x8, x7, x6
    bgeu  x7, x6, BYTE1_DONE
    sub   x8, x6, x7

BYTE1_DONE:
    add   x3, x3, x8


# ------------------------------------------------------------
# Byte 2
# ------------------------------------------------------------

    srli  x6, x1, 16
    srli  x7, x2, 16

    andi  x6, x6, 255
    andi  x7, x7, 255

    sub   x8, x6, x7
    bgeu  x6, x7, BYTE2_DONE
    sub   x8, x7, x6

BYTE2_DONE:
    add   x3, x3, x8


# ------------------------------------------------------------
# Byte 3
# ------------------------------------------------------------

    srli  x6, x1, 24
    srli  x7, x2, 24

    sub   x8, x7, x6
    bgeu  x7, x6, BYTE3_DONE
    sub   x8, x6, x7

BYTE3_DONE:
    add   x3, x3, x8


# ------------------------------------------------------------
# End - Infinite Loop
# ------------------------------------------------------------

END:
    jal x0, END